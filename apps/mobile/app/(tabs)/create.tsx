  page: { flex: 1, backgroundColor: '#101310' }, content: { paddingHorizontal: 22, paddingTop: 20, paddingBottom: 42 },
  back: { flexDirection: 'row', alignItems: 'center', gap: 9, marginBottom: 29 }, backText: { color: '#a2a89f', fontFamily: 'SpaceGrotesk_600SemiBold', fontSize: 10, letterSpacing: 1.2 },
